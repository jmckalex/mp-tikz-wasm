/**
 * TeX transcript parser tests. The fixtures in test/unit/fixtures/tex-logs are excerpts of real
 * TeX Live 2025 logs, run with -interaction=nonstopmode:
 * - lualatex-fontspec: LuaHBTeX 1.22, `\setmainfont{NoSuchFontAnywhere}` (line 3), errors at line 4;
 * - pdflatex-errors: pdfTeX, a \PackageError with help (line 4), an undefined control sequence (5), an
 *   \errmessage longer than a log line with UTF-8 in it (6), a \GenericError for a class (7);
 * - lualatex-l3-errors: LuaHBTeX, an expl3 \msg_error with two help paragraphs (6), then LaTeX's own
 *   unknown-environment error (7).
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseTexLogDocument } from '../../src/ts/core.js';
import { logLines, logText, texErrorMessage, texLogLine } from '../../src/ts/tex/bridge.js';
import { repoRoot } from './oracle.js';

const log = (name: string): string => readFileSync(join(repoRoot, 'test', 'unit', 'fixtures', 'tex-logs', `${name}.log.txt`), 'utf8');
const errors = (name: string) => parseTexLogDocument(log(name), 'doc.tex').filter((d) => d.severity === 'error');

describe('parseTexLogDocument', () => {
  it('reads a package error whose first line is empty from its (name) lines', () => {
    const d = errors('lualatex-fontspec');
    expect(d).toHaveLength(4);
    expect(d[0]).toMatchObject({ severity: 'error', source: 'tex', file: 'doc.tex', line: 4 });
    expect(d[0].message).toBe('Package fontspec Error: The font "NoSuchFontAnywhere" cannot be found; this may be but usually is not a fontspec bug. '
      + 'Either there is a typo in the font name/file, the font is not installed (correctly), or there is a bug in the underlying font loading engine (XeTeX/luaotfload).');
  });
  it('keeps a LaTeX3 message\'s help, which follows an empty line, paragraphs and all', () => {
    const d = errors('lualatex-fontspec');
    expect(d[0].help).toEqual(['A font might not be found for many reasons.', ' Check the spelling, where the font is installed etc. etc.', '', ' When in doubt, ask someone for help!']);
    const l3 = errors('lualatex-l3-errors');
    expect(l3.map((x) => [x.message, x.line])).toEqual([['Package mymod Error: Bad thing happened.', 6], ['LaTeX Error: Environment nosuchenv undefined.', 7]]);
    expect(l3[0].help).toEqual(['First help line.', 'Second line.', '', 'Third paragraph.']);
    expect(l3[1].help).toEqual(['Your command was ignored.', 'Type  I <command> <return>  to replace it with another command,', 'or  <return>  to continue without it.']);
  });
  it('keeps the help that follows the context at once, as before', () => {
    const d = errors('pdflatex-errors');
    expect(d.map((x) => [x.message, x.line])).toEqual([
      ['Package foo Error: Bad thing happened here.', 4],
      ['Undefined control sequence.', 5],
      ['A long message: Größe äöü that runs on and on past the seventy-nine column mark of TeX\'s log.', 6],
      ['Class bar Error: short.', 7],
    ]);
    expect(d[0].help).toEqual(['Help one.', 'Help two.']);
    expect(d[1].help).toHaveLength(5);
    expect(d[1].help?.[0]).toBe('The control sequence at the end of the top line');
    expect(d[2].help?.[0]).toBe('This error message was generated by an \\errmessage');
    expect(d[3].help).toEqual(['Class help.']);
  });
  it('joins an error line TeX broke after 79 bytes (pdfTeX) or 80 (LuaTeX, a font\'s error)', () => {
    // pdflatex-errors: the \errmessage, 79 bytes with five two-byte letters; lualatex-fontspec: the font, 80
    expect(errors('pdflatex-errors')[2].message).toMatch(/column mark of TeX's log\.$/);
    const font = errors('lualatex-fontspec')[3];
    expect(font.message).toBe('Font \\TU/NoSuchFontAnywhere(0)/m/n/10=name:NoSuchFontAnywhere:mode=node;language=dflt;+tlig; at 10pt not loadable: metric data not found or bad.');
    expect(font.line).toBe(4);
    expect(font.help?.[0]).toBe('I wasn\'t able to read the size data for this font,');
  });
});

describe('texLogLine', () => {
  const x = (n: number) => 'x'.repeat(n);
  it('joins a line of 79 or 80 bytes with the next', () => {
    expect(texLogLine([x(79), 'y', 'z'], 0)).toEqual({ text: x(79) + 'y', last: 1 });
    expect(texLogLine([x(80), x(79), 'y'], 0)).toEqual({ text: x(80) + x(79) + 'y', last: 2 });
  });
  it('leaves a line that ends there by itself: the next is empty or opens the context', () => {
    expect(texLogLine([x(79), '', 'y'], 0)).toEqual({ text: x(79), last: 0 });
    expect(texLogLine(['! ' + x(77), 'l.5 \\foo'], 0)).toEqual({ text: '! ' + x(77), last: 0 });
    expect(texLogLine(['! ' + x(77), '<to be read again> '], 0)).toEqual({ text: '! ' + x(77), last: 0 });
    expect(texLogLine([x(78), 'y'], 0)).toEqual({ text: x(78), last: 0 });
    expect(texLogLine([x(81), 'y'], 0)).toEqual({ text: x(81), last: 0 });
  });
  // a log as bytes: TeX's lines, from the .log's bytes or from text
  const bytes = (...parts: (string | number[])[]) => Uint8Array.from(parts.flatMap((p) => (typeof p === 'string' ? [...new TextEncoder().encode(p)] : p)));
  const joined = (log: Uint8Array | string) => { const l = logLines(log); const r = texLogLine(l, 0); return { text: logText(r.text), last: r.last }; };
  it("joins pdfTeX's letter split at the 79th byte, from the log's bytes", () => {
    // ü is C3 BC: pdfTeX wrote C3 as the line's 79th byte and BC first on the next
    const log = bytes(x(78), [0xc3, 0x0a, 0xbc], 'yz\n');
    expect(joined(log)).toEqual({ text: x(78) + 'üyz', last: 1 });
    expect(new TextDecoder().decode(log)).toBe(x(78) + '\ufffd\n\ufffdyz\n');   // what texLog has: the letter is lost
  });
  it("joins LuaTeX's line ended early: a letter of k bytes that would end on byte 79 or later", () => {
    expect(joined(`${x(77)}\nüyz`)).toEqual({ text: x(77) + 'üyz', last: 1 });     // 77 + 2 = 79
    expect(joined(`${x(78)}\nüyz`)).toEqual({ text: x(78) + 'üyz', last: 1 });
    expect(joined(`${x(76)}\n€yz`)).toEqual({ text: x(76) + '€yz', last: 1 });     // 76 + 3
    expect(joined(`${x(75)}\n𝄞yz`)).toEqual({ text: x(75) + '𝄞yz', last: 1 });    // 75 + 4
    expect(joined(`${x(76)}\nüyz`)).toEqual({ text: x(76), last: 0 });             // 76 + 2: ü fitted
    expect(joined(`${x(77)}\nayz`)).toEqual({ text: x(77), last: 0 });             // an ASCII letter fitted
    expect(joined(`ä${x(76)}\nüyz`)).toEqual({ text: `ä${x(76)}üyz`, last: 1 });  // 2 + 76 = 78 bytes, 77 letters
  });
  it('reads text as its UTF-8 bytes, and gives text back', () => {
    expect(logLines('a\nb')).toEqual(['a', 'b']);
    expect(logText(logLines('Größe — ok')[0])).toBe('Größe — ok');
    expect(logLines('ä')[0]).toHaveLength(2);
    const [e] = parseTexLogDocument('! Undefined control sequence.\nl.3 \\Größe\n\nDie Größe ist unbekannt.\n\n', 'doc.tex');
    expect(e).toMatchObject({ message: 'Undefined control sequence.', line: 3, help: ['Die Größe ist unbekannt.'] });
  });
});

describe('texErrorMessage', () => {
  it('joins a class error\'s continuation lines to its first', () => {
    const lines = ['! Class foo Error: The option `bar\' is', '(foo)                not known.', '', 'l.1 x'];
    expect(texErrorMessage(lines, 0)).toBe('Class foo Error: The option `bar\' is not known.');
  });
  it('leaves other errors as their first line', () => {
    expect(texErrorMessage(['! Undefined control sequence.', 'l.3 \\foo'], 0)).toBe('Undefined control sequence.');
    expect(texErrorMessage(['! LaTeX Error: File `nosuch.sty\' not found.', ''], 0)).toBe('LaTeX Error: File `nosuch.sty\' not found.');
    // another package's (name) lines are not this error's
    expect(texErrorMessage(['! Package foo Error: Bad.', '(bar)                Other.'], 0)).toBe('Package foo Error: Bad.');
  });
});
